# simple maths can be done in R
print(1 +3)

print(4-1)

# we also have built in maths function
min(12, 4, 5)
max(12, 4, 5)

# Gets the square root of a number 
sqrt(25)

# gets the absolute value of a number
abs(-100)

# We can round numbers upwards using ceiling and floor
ceiling(1.4) # rounds the number 1.4 upwards to its nearest integer. This will give 2

floor(1.4) # rounds the number 1.4 downwards to its nearest integer. This will give 1
